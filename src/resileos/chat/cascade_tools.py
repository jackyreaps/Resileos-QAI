"""Tools built from the cascade math, for the composer and Studio.

Everything here is computed from existing constructions; no outside
model or provider is called:

- ``address_upload``: each perceived upload gets a pin address on the
  five-pin cascade (Human Belt 5, frames 3/5/9/12, waist 36, keep floor
  1/64) and a chroma belt code (``resileos.ui.chroma``) so search and
  Studio can reuse it.
- ``rank_sources``: Hermes-style search/crawl envelopes indexed by
  cascade address and belt, ranked with φ-level weights, dropped below
  the 1/64 floor, capped at the waist.
- ``variations_from_code`` / ``clip_from_code``: pictures and clips
  generated by expanding the chroma code (belt rotation, RBY
  permutation, φ hue steps) and stepping it with the φ / magnetic-phase
  motion scale. ``clip_metrics`` are recorded on every clip.
- ``use_factor`` / ``FactorPool``: content-free residual factors from
  use, aggregated for the local hub and offered to Eat as an envelope.
  Morpheus turns the aggregate into unverified dream candidates.

Nothing here calls learn, writes Titanos, or writes a scar.
"""
